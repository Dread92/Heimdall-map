_HYPH_RX = re.compile(r"([а-яіїєґ']+)\s+[-–]\s+([а-яіїєґ']+)")
_ROUTE_RX = re.compile(r"^\W*([а-яіїєґ' ]+?)\s+[-–→]\s+([а-яіїєґ' ]+?)(?=\s|$|[.,!])")
_PLANE_RX = re.compile("\u2708")          # ✈


def _join_hyphenated(t):
    """"конча - заспа" is one suburb, Конча-Заспа, not a route from Koncha to Zaspa. Joined only when the joined
    form is a place the gazetteer knows, so "димерка - бровари" stays a route."""
    known = {_norm(k) for k in PLACES}
    return _HYPH_RX.sub(lambda m: f"{m.group(1)}-{m.group(2)}" if f"{m.group(1)}-{m.group(2)}" in known else m.group(0), t)


def _live_lines(text, uid):
    """"✈️Вишневе / ✈️Петрівці" is two drones at two places. Split one post into one mark per line, but only
    when every line is short and names exactly one place — otherwise it is a sentence and goes whole."""
    lines = [ln.strip() for ln in text.split("\n") if ln.strip()]
    if len(lines) < 2:
        return None
    out = []
    for ln in lines:
        tl = _route_arrows(_join_hyphenated(_norm(prepare(ln))), uid)
        if len(tl.split()) > 4:
            return None
        pl = _find_places(tl, uid)
        if len(pl) != 1:
            if pl or _status_of(tl):
                return None          # a line with two places or an outcome word: not a simple list
            continue                 # a line with no place at all ("нові з чернігівщини") adds nothing
        out.append(ln)
    return out if len(out) >= 2 else None


_HEIGHT_NUM = r"(?<![\d.,])\d{3,4}(?![\d.,])"


def _height_only(t):
    """1.54.7: a post that is a height and nothing else ("500", "400 м", "↓600", "Увага 500", "1200 знижується") — the
    height (as parse_altitude gives it), or None."""
    nums = re.findall(_HEIGHT_NUM, t)
    if len(nums) != 1:
        return None
    rest = re.sub(_HEIGHT_NUM + r"|увага|уважно|висот\w*|зниж\w*|набира\w*|низько|метр\w*|(?<![а-яіїєґ])м(?![а-яіїєґ])"
                  r"|(?<![a-z])m(?![a-z])", " ", t)
    if re.search(r"[а-яіїєґыэa-z\d]", rest):
        return None
    v = int(nums[0])
    if not 100 <= v <= 9000:
        return None
    return dict(_alt_full(t) or {"state": None, "matched": nums[0]}, m=v)


def _parse_live(text, uid):
    """@kyiv_airdef live tracking: bare place names, one per post ('ДВРЗ', 'Позняки', 'ТЕЦ-5 уважно'),
    outcome words on their own ('Впав', 'Знижується', 'Збили'), occasionally full sentences.
    Returns markers; status posts without a place get 'needs_context' so the server can place them at the
    channel's previous position."""
    split = _live_lines(text, uid)
    if split:
        return [m for ln in split for m in _parse_live(ln, uid)]
    home = uid if uid not in ("31", "14") else None      # 1.43: a regional channel's villages, for parse_post too
    t = _route_arrows(_join_hyphenated(_norm(prepare(text))), uid)
    kept = _drop_clear_sentences(t)         # "Чисте небо … Київ. Васильків увага" → only Vasylkiv is a warning
    if kept != t and kept.strip():
        text, t = kept, kept
    if len(t.split()) > 8 or re.search(r"курс|напрям|у бік|летить", t):
        r = parse_post(text, home)
        if r:
            return r
    if re.search(r"укритт|тривог|відбій", t) and not re.search(r"курс|йде|летить|над\b", t):
        return []          # shelter / alert warning / all-clear (1.45), not a position report
    st = _status_of(t)
    # 1.54.7: a height and nothing else — "500", "400" (@chyste_nebo, 01:21, between "Куладинці" and "Кулажинці") — is
    # the height of the target this channel reported last: carried to that report by the server (needs_context), never
    # a place of its own. Read from @chyste_nebo it was dropped, and the drone at 400 m north-east of Brovary was not shown.
    ho = None if st else _height_only(t)
    if ho:
        return [{"type": "unknown", "status": None, "lon": None, "lat": None, "heading": None, "place": None, "target": None,
                 "count": None, "jet": False, "oblast_uid": uid, "needs_context": True, "height_only": True, "live": True,
                 "likely": "drones", "alt": ho,
                 "evidence": {"segment": t.strip(), "type": {"matched": None, "confidence": "none",
                                                             "method": "a height alone — the target this channel reported last"},
                              "position": {"matched": None, "place": None, "confidence": "medium",
                                           "method": "no place in this post — placed at the channel's previous report"},
                              "heading": None, "count": None}}]
    places = _find_places(t, uid)
    if st and not places:
        sm = next((rx.search(t) for n, rx in STATUS_RX if n == st), None)
        return [{"type": "drones", "status": st, "lon": None, "lat": None, "heading": None, "place": None, "target": None, "count": None, "jet": False,
                 "oblast_uid": uid, "needs_context": True,
                 "evidence": {"segment": t.strip(), "type": {"matched": sm.group(0) if sm else st, "method": "outcome keyword"},
                              "position": {"matched": None, "place": None, "method": "no place in this post — placed at the channel's previous report", "confidence": "medium"},
                              "heading": None, "count": None}}]
    if not places:
        return []
    if len(t.split()) > 6 and not re.search(r"уважн|йде|летить|на\b|бік|→", t):
        return parse_post(text, home)
    # Where it is, and where it is going, by the words before each place — not "the last place when the post says
    # 'на'", which put "Від Глевахи два на Васильків" on Vasylkiv while it was still at Hlevakha.
    roles = [(p_, _place_role(t, p_)) for p_ in places]
    # 1.44.1: "курсом в бік Велика Рибиця/Мала Рибиця/Осоївка" (@kabusumy) — every name of a list after "в бік" is a place
    # it may be heading to. Read as a bare name, "Мала Рибиця" became where the target IS: a position nobody stated.
    for i in range(1, len(roles)):
        if roles[i][1] is None and roles[i - 1][1] == "dest" and _LIST_SEP_RX.fullmatch(t[roles[i - 1][0][1]:roles[i][0][0]]):
            roles[i] = (roles[i][0], "dest")
    at = next((p_ for p_, r in roles if r == "from"), None) or next((p_ for p_, r in roles if r is None), None)
    dest = next((p_ for p_, r in roles if r == "dest" and (not at or p_[2] != at[2])), None)
    dest_only = at is None
    s, e, name = at or dest
    lon, lat, uid = PLACES[name]
    mtype = None
    for n, rx in TYPE_RX:
        if rx.search(t):
            mtype = n
            break
    # A bare place name on a live-tracking channel says WHERE, not WHAT: shown as an unspecified threat.
    # Except ✈️: these channels prefix every drone report with it ("✈️Новий БпЛА з Чернігівщини", "БпЛА на
    # Бориспіль✈️"), so on them it is the type, written as a symbol. Not globally — elsewhere ✈️ also marks
    # aviation, and "✈️ активність авіації" read as a Shahed would be a type nobody stated.
    plane = mtype is None and bool(_PLANE_RX.search(text)) and not re.search(r"авіац|літак|борт", t)
    if plane:
        mtype = "drones"
    stated = mtype is not None
    mtype = mtype or "unknown"
    cnt = None
    mc = COUNT_RX.search(t)
    if mc:
        cnt = int(mc.group(1) or mc.group(2))
    alt = _alt_full(t)
    if alt and alt.get("m") and cnt == alt["m"]:
        cnt = None                      # "1600, Вороньків" is a height, never a count of 1600 drones
    heading, hev = None, {"matched": None, "method": "derived from the previous report of this channel when available", "confidence": "medium"}
    pos_ev = {"matched": name, "place": name, "method": "bare place name = current position of the tracked target (gazetteer)", "confidence": "high"}
    target = None
    if dest and not dest_only:
        target = dest[2]
        blon, blat, _ = PLACES[target]
        heading = round(bearing(lon, lat, blon, blat))
        hev = {"matched": t[at[0]:dest[1]].strip(), "method": f"at {name}, heading for {target} (the place after 'на' / 'в район' is where it is going)", "confidence": "medium"}
    elif dest_only:
        target = name
        pos_ev = {"matched": t[max(0, s - 12):e].strip(), "place": name, "confidence": "low",
                  "method": "only where it is going was given — placed at this channel's previous report when there is one, otherwise drawn at the destination"}
    rm = _ROUTE_RX.search(t)
    arrow = t.find("→")
    if arrow > 0 and len(places) >= 2:
        # 1.43: a route the post wrote with a dash between two places ("Любеч-Славутич", "Лесное - Пятихатки"): at
        # the last place before the dash, heading for the first one after it
        a = [p_ for p_ in places if p_[1] <= arrow]
        b = [p_ for p_ in places if p_[0] > arrow]
        if a and b and a[-1][2] != b[0][2]:
            name, bname = a[-1][2], b[0][2]
            lon, lat, uid = PLACES[name]
            blon, blat, _ = PLACES[bname]
            heading = round(bearing(lon, lat, blon, blat))
            target, dest_only = bname, False
            pos_ev = {"matched": name, "place": name, "method": "first place of a route written 'A-B' in the post (gazetteer)", "confidence": "high"}
            hev = {"matched": t[a[-1][0]:b[0][1]].strip(), "method": "route written 'A - B' in the post: at A, heading for B", "confidence": "medium"}
    elif rm and len(places) >= 2:
        a = _find_places(rm.group(1), uid)
        b = _find_places(rm.group(2), uid)
        if a and b and a[0][2] != b[0][2]:
            name, bname = a[0][2], b[0][2]
            lon, lat, uid = PLACES[name]
            blon, blat, _ = PLACES[bname]
            heading = round(bearing(lon, lat, blon, blat))
            hev = {"matched": rm.group(0).strip(), "method": "route written 'A - B' in the post: at A, heading for B", "confidence": "medium"}
    kind_ev = ("keyword" if (stated and not plane) else
               "✈️ — this channel's mark for a drone report" if plane else
               "the post names only a place — this channel tracks strike drones, but it did not say so here")
    return [{"type": mtype, "status": st, "lon": round(lon, 3), "lat": round(lat, 3), "heading": heading,
             "place": ("→ " + name) if dest_only else name, "target": target, "count": cnt,
             "approach": dest_only, "dest_only": dest_only,
             "alt": alt,
             "jet": bool(JET_RX.search(t)), "oblast_uid": uid, "live": True, "likely": (None if stated else "drones"),
             "evidence": {"segment": t.strip(), "type": {"matched": ("✈️" if plane else "(none)"), "method": kind_ev, "confidence": ("high" if (stated and not plane) else "medium" if plane else "none")},
                          "position": pos_ev,
                          "heading": hev, "count": None}}]


_ERADAR_LIVE = re.compile(r"(\d{1,3})\s+на\s+([А-ЯІЇЄҐ][^\d\n]+?)(?=\s+\d{1,3}\s+на\s|\s*$|[.,;!])", re.M)
_ERADAR_SUM = re.compile(r"([А-ЯІЇЄҐ][а-яіїєґ'\-]+ська)\s+область((?:\s*◦[^\n]*\n?)+)")


def parse_eradar_summary(text):
    """@eRadarrua situation summaries: 'Сумська область ◦ Ударний Бп 3 грп. ◦ Реактивний 1 грп.' per oblast.
    Returns {oblast_uid: {'drones': n, 'jet': n, 'missiles': n}} or None. Group counts, not positions."""
    if "◦" not in text:
        return None
    out = {}
    for m in _ERADAR_SUM.finditer(text):
        adj, body = m.group(1).lower(), m.group(2).lower()
        uid = None
        for stem, u in OBLAST_STEM:
            if adj.startswith(stem):
                uid = u
                break
        if not uid:
            continue
        d = {"drones": 0, "jet": 0, "missiles": 0}
        for item in body.split("◦"):
            n = re.search(r"(\d{1,3})\s*грп", item)
            if not n:
                continue
            if "реактив" in item:
                d["jet"] += int(n.group(1))
            elif "ракет" in item or "крилат" in item or "баліст" in item:
                d["missiles"] += int(n.group(1))
            elif "бп" in item or "бпла" in item or "дрон" in item:
                d["drones"] += int(n.group(1))
        out[uid] = d
    return out or None


def parse_eradar(text):
    """@eRadarrua: summaries (per-oblast group counts, no positions → no markers) and live lines
    '1 на Велику Димерку 2 на Баришівку' = N drones heading for <place> (current threat to that town)."""
    if "◦" in text:
        return []
    t = _norm(text)
    if len(t) > 160 or not _ERADAR_LIVE.search(text):
        return parse_post(text)
    out = []
    for m in _ERADAR_LIVE.finditer(text):
        cnt, seg = int(m.group(1)), m.group(2)
        pl = _find_places(_norm(seg), "14")
        if not pl:
            continue
        s_, e_, name = pl[0]
        lon, lat, uid = PLACES[name]
        out.append({"type": "drones", "status": None, "lon": round(lon, 3), "lat": round(lat, 3), "heading": None, "place": name, "target": name,
                    "count": cnt, "jet": bool(JET_RX.search(t)), "oblast_uid": uid, "live": True,
                    "evidence": {"segment": m.group(0).strip(), "type": {"matched": "(none)", "method": "channel convention: @eRadarrua live lines count drones heading for a town"},
                                 "position": {"matched": seg.strip(), "place": name, "method": "town the drones are reported heading to (drawn at the town — they are approaching it, exact position not given)", "confidence": "medium"},
                                 "heading": {"matched": None, "method": "not given — target town only", "confidence": "none"}, "count": {"matched": m.group(1), "method": "number before 'на'"}}})
    return out


