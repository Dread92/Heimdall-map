# 1.51: where a post says a target comes from — the first letter of the target's tag (N-07, S-12…). Only when the post
# says so: never worked out from where it was first reported (a jet first seen over Chernihiv oblast may have come
# from Belarus or from Russia). A Ukrainian oblast or town it comes from is a place, not an origin.
_ORIGIN_RX = [
    ("belarus", re.compile(r"(?:\bз|\bзі|\bіз|\bвід|\bс|\bсо|\bиз)\s+(?:території\s+|боку\s+|сторони\s+|территории\s+|стороны\s+)?"
                           r"(?:республіки\s+|республики\s+)?(?:білорус\w*|беларус\w*|рб\b|білорусь)")),
    ("russia", re.compile(r"(?:\bз|\bзі|\bіз|\bвід|\bс|\bсо|\bиз)\s+(?:території\s+|боку\s+|сторони\s+|территории\s+|стороны\s+)?"
                          r"(?:рос(?:ії|ии)\b|рф\b|брянщин\w*|курщин\w*|бєлгородщин\w*|білгородщин\w*|белгородск\w*|брянськ\w*|"
                          r"брянск\w*|курськ\w*|курск\w*|бєлгород\w*|білгород\w*|белгород\w*|орловщин\w*|смоленщин\w*)")),
    ("sea", re.compile(r"(?:\bз|\bзі|\bіз|\bс|\bсо|\bиз)\s+(?:боку\s+|стороны\s+)?(?:моря\b|акваторі\w+|чорного\s+моря|черного\s+моря|"
                       r"азовського\s+моря)")),
    ("crimea", re.compile(r"(?:\bз|\bзі|\bіз|\bс|\bсо|\bиз)\s+(?:боку\s+|стороны\s+)?(?:тимчасово\s+окупованого\s+)?(?:криму|крыма)\b")),
    ("occupied", re.compile(r"(?:\bз|\bзі|\bіз|\bс|\bиз)\s+(?:тот\b|тимчасово\s+окупован\w+\s+територ\w+|окупован\w+\s+територ\w+|"
                            r"оккупированн\w+\s+территор\w+)")),
]
_DIR8 = ("n", "ne", "e", "se", "s", "sw", "w", "nw")


def stated_origin(seg):
    """{"o": belarus|russia|sea|crimea|occupied|n|ne|e|se|s|sw|w|nw, "q": the words} or None — what the post says."""
    low = (seg or "").lower()
    for o, rx in _ORIGIN_RX:
        m = rx.search(low)
        if m:
            return {"o": o, "q": seg[m.start():m.end()].strip()}
    m = _FROM_COMPASS.search(low)
    if m:
        deg = _dir(m.group(1))
        if deg is not None:
            return {"o": _DIR8[int(((deg % 360) + 22.5) // 45) % 8], "q": seg[m.start():m.end()].strip()}
    return None


_SPEED_RX = re.compile(r"(?:швидк\w*|скорост\w*)\s*(?:~|бл\.|близько|около|до|понад)?\s*(\d{2,4})\s*(?:км/?\s*(?:год|г|ч)\w*|км)?"
                       r"|(\d{2,4})\s*км\s*/\s*(?:год|г|ч)\w*", re.I)


def parse_speed(seg):
    """{"kmh": n, "q": the words} when the post states a speed ("швидкість 180 км/год", "400 км/год") — never derived."""
    m = _SPEED_RX.search(seg or "")
    if not m:
        return None
    v = int(m.group(1) or m.group(2))
    return {"kmh": v, "q": m.group(0).strip()} if 30 <= v <= 5000 else None


def _telemetry(ms, text):
    """The origin and the speed each mark's own words state (its segment; the whole post when it reports one target)."""
    for m in ms:
        seg = (m.get("evidence") or {}).get("segment") or (text if len(ms) == 1 else "")
        o = stated_origin(seg) or (stated_origin(text) if len(ms) == 1 else None)
        sp = parse_speed(seg) or (parse_speed(text) if len(ms) == 1 else None)
        if o:
            m["origin"] = o
        if sp:
            m["speed"] = sp
    return ms


def parse_for_channel(channel, text, near=None):
    """`near` (1.45): the oblasts this regional channel named in its last posts. A tracker follows its targets into the
    next oblast — "Це він на Хмельниччині", then "Маневр на Гулівці", "Далі на Кути" (@rivne_radar): a post that names
    nothing of its own oblast is read against those."""
    text = prepare(text, channel)
    ms = [m for m in _parse_for_channel(channel, text, near) if m.get("type") not in NEVER_PLACED]
    home = CHANNEL_HOME.get(channel)
    if ms and home and home not in ("31", "14"):
        # 1.45: a regional tracker's place 300 km and more from its oblast, in an oblast the post does not name, is a
        # misreading — "Велика Бобровиця" (@rivne_radar, a village next to Rivne) was the town of Бобровиця in
        # Chernihiv oblast
        named = set(oblasts_named(text)) | set(near or ()) | {home}
        hc = _OBL_CENTRE.get(home)
        ms = [m for m in ms if m.get("lon") is None or m.get("oblast_uid") in named or not hc
              or _km((m["lon"], m["lat"]), hc) <= 300]
    return _telemetry([_city_settle(_rel_settle(_raion_settle(_settle(m)))) for m in ms], text)


# 1.45.1: "БпЛА на півночі від Миколаєва, курс на захід" (the Air Force) is north OF the city, at a distance the post
# does not give. It was drawn ON Mykolaiv, "town in gazetteer, high confidence, ±5 km".
_REL_RX = re.compile(r"(?:(\d{1,3})\s*км\s+)?(?:\b(?:на|в|у)\s+((?:півн|півд)[а-яіїє]*(?:[\s-]+(?:сх|зах)[а-яіїє]*)?|(?:сх|зах)[а-яіїє]*)\s+від"
                     r"|\b((?:північно|південно)-?(?:східн|західн)іше|північніше|південніше|східніше|західніше)(?:\s+від)?)\s+([а-яіїєґ'\-]+)")


_OBL_CAPITAL = {"4": "Вінниця", "8": "Луцьк", "9": "Дніпро", "10": "Житомир", "11": "Ужгород", "12": "Запоріжжя",
                "13": "Івано-Франківськ", "15": "Кропивницький", "16": "Луганськ", "17": "Миколаїв", "18": "Одеса",
                "19": "Полтава", "5": "Рівне", "20": "Суми", "21": "Тернопіль", "22": "Харків", "23": "Херсон",
                "3": "Хмельницький", "24": "Черкаси", "26": "Чернівці", "25": "Чернігів", "27": "Львів", "28": "Донецьк",
                "29": "Сімферополь", "31": "Київ"}


def _stem4(w):
    """The first four letters of a name, its vowels that alternate in declension made one: Київ / Києва, Харків / Харкова."""
    return re.sub(r"[іїєеи]", "*", w.lower().replace("'", "").replace("’", ""))[:4]


def _rel_settle(m):
    """A place the post gives as the reference of a side — "на півночі від X", "північніше X", "за 20 км на північ від X"
    — is not where the target is. With a distance, the mark goes that far that way. Without one: from an oblast's
    capital (or Kyiv), the oblast is marked — "north of Mykolaiv" can be anywhere in its northern half — and from any
    other town, the mark stays at the town with low confidence; either way the card says "north of X"."""
    p = m.get("place") or ""
    if m.get("status") or m.get("approach") or not p or p.startswith("→ ") or p == "область" or p not in PLACES:
        return m
    ev = dict(m.get("evidence") or {})
    seg = ev.get("segment") or ""
    base = _stem4(p.split(" (")[0])
    for r in _REL_RX.finditer(seg):
        if _stem4(r.group(4)) != base:
            continue
        deg = _dir(r.group(2) or r.group(3) or "")
        if deg is None:
            continue
        lon, lat, uid = PLACES[p]
        pos = dict(ev.get("position") or {})
        pos.update(rel=deg, ref=p, matched=r.group(0).strip())
        if r.group(1):
            km = int(r.group(1))
            m["lat"] = lat + km * math.cos(math.radians(deg)) / 111.0
            m["lon"] = lon + km * math.sin(math.radians(deg)) / (111.0 * math.cos(math.radians(lat)))
            pos.update(confidence="medium", method=f"{km} km from {p} toward {deg}°, as the post said")
        elif _OBL_CAPITAL.get(uid) == p:
            m["place"] = "область"
            m["oblast_uid"] = "14" if uid == "31" else uid
            pos.update(place="oblast", confidence="low",
                       method=f"a side of {p}, the oblast's capital, and no distance: the oblast is marked, not a point")
        else:
            pos.update(confidence="low", method=f"a side of {p} and no distance: drawn at {p}, which it is not at")
        ev["position"] = pos
        m["evidence"] = ev
        break
    return m


# 1.49: "Київ" alone — "над Києвом", "біля Києва", "на околицях правого берега Києва" — says the city, not where in it.
# A city 30 km across was drawn as a point at its centre, "town in gazetteer, high confidence, ±5 km": a resident read
# a drone over the centre that nobody had put there. Kyiv has its own outline on the map, so the city is marked, not a
# point — as an oblast is — with the bank when the post names one. A district, a street, a landmark, a distance and
# a side ("20 км на північ від Києва") keep their point; a course to Kyiv ("→ Київ") stays an approach.
_BANK_RX = re.compile(r"\b(прав|лів)\w*\s+берег\w*", re.I)


def _city_settle(m):
    if m.get("place") != "Київ" or m.get("approach"):
        return m
    ev = dict(m.get("evidence") or {})
    pos = dict(ev.get("position") or {})
    if pos.get("rel") is not None:
        return m
    m["place"] = "область"
    m["oblast_uid"] = "31"
    pos.update(place="oblast", confidence="low",
               method="Kyiv named and no place in it: the city is marked, not a point at its centre")
    b = _BANK_RX.search(ev.get("segment") or "")
    if b:
        pos["bank"] = "right" if b.group(1).lower() == "прав" else "left"
    ev["position"] = pos
    m["evidence"] = ev
    return m


def _raion_settle(m):
    """1.45: a raion is an area, not a point. "Залітає у Гайсинський район … курсом на Теплик" was drawn at Гайсин, the
    raion's centre town, with a course from there to Теплик — a position and a heading nobody gave. With a town it is
    heading for, it is drawn as an approach to that town; alone, at the centre town, with low confidence."""
    p = m.get("place") or ""
    if m.get("status") or not p.endswith(" р-н"):
        return m
    ev = dict(m.get("evidence") or {})
    pos = dict(ev.get("position") or {})
    t = m.get("target")
    if t and t in PLACES and not t.endswith(" р-н") and not m.get("approach"):
        lon, lat, uid = PLACES[t]
        m.update(place="→ " + t, lon=lon, lat=lat, approach=True, dest_only=True, heading=None)
        if uid:
            m["oblast_uid"] = uid
        pos.update(place=t, confidence="low", method="the post named the raion it is in and the town it is heading for — "
                                                     "drawn at that town, as an approach; a raion's centre is not a position")
        ev["heading"] = {"matched": None, "method": "no course from a raion's centre", "confidence": "none"}
    else:
        pos.update(confidence="low", method=(pos.get("method") or "") + " — a raion named, drawn at its centre town")
    ev["position"] = pos
    m["evidence"] = ev
    return m


def oblasts_named(text, channel=None):
    """The oblasts a post names, in order — for the server's `near` context."""
    return [uid for _, uid, _, _ in _find_oblasts_all(_norm(prepare(text or "", channel)))]


def _settle(m):
    """A marker whose place is a name several villages share: the candidates go with it, best first, for the server
    to pick the one nearest the channel's previous report — or, with nothing to go on and no clear default (the only
    raion/hromada centre, the only city district, by far the largest), to leave it off the map."""
    for fld in ("place", "target"):
        v = m.get(fld)
        if not v or not isinstance(v, str):
            continue
        pre = "→ " if v.startswith("→ ") else ""
        a = AMBIG.get(v[len(pre):])
        if not a:
            continue
        first = a["keys"][0]
        if fld == "place" or m.get("dest_only"):
            m["candidates"] = [[k, PLACES[k][0], PLACES[k][1], PLACES[k][2]] for k in a["keys"][:8]]
            m["ambiguous"] = not a["default"]
            m[fld] = pre + first
            ev = dict(m.get("evidence") or {})
            pos = dict(ev.get("position") or {})
            pos["place"] = first
            note = (" — several villages of the oblast are called " + a["name"] +
                    ("; the raion/hromada centre or by far the largest, unless the channel's previous report is near another"
                     if a["default"] else "; placed only next to this channel's previous report"))
            if note not in (pos.get("method") or ""):         # place and target both settle: said once
                pos["method"] = (pos.get("method") or "") + note
            pos["confidence"] = "medium" if a["default"] else "low"
            ev["position"] = pos
            m["evidence"] = ev
        elif a["default"]:
            m[fld] = first
        else:
            # where it is going is a name several villages share and nothing says which: no course is drawn to it
            m[fld] = None
            m["heading"] = None
            ev = dict(m.get("evidence") or {})
            ev["heading"] = {"matched": a["name"], "confidence": "none",
                             "method": "the destination is a name several villages of the oblast share — no course drawn"}
            m["evidence"] = ev
    return m


# 1.41.2: "1 знищено.\nНаступний Нивки" (@eRadarrua, 6 Oct 2026, 05:45) is two reports: one target destroyed —
# where, the line does not say — and the NEXT one at Nyvky. Read as one sentence it was a confirmed shoot-down at
# Nyvky, kept for 24 hours in the history layer. A sentence that starts with "наступний", "ще один", "другий" or
# "інший" after an outcome is another target: the outcome keeps only what its own words say (on a live channel, the
# channel's previous position; otherwise nothing), and the place after the word is the next target's position.
NEXT_RX = re.compile(r"(?:^|(?<=[.!?;\n]))\s*(?:наступн(?:ий|а|і|ого)|ще\s+(?:один|одна|одного)|друг(?:ий|а)|інш(?:ий|а))\b", re.I)


def _split_next(text):
    """(the outcome, the next target) when an outcome is followed by a sentence about the next target, else None."""
    t = _norm(text)
    m = NEXT_RX.search(t)
    if not m or not t[:m.start()].strip():
        return None
    before, after = text[:m.start()].strip(), text[m.end():].strip(" :—–-\n")
    if not any(rx.search(_norm(before)) for _, rx in STATUS_RX):
        return None
    return before, after


def _parse_for_channel(channel, text, near=None):
    if channel == "eRadarrua" and "◦" in text:
        return []          # per-oblast group-count summary: counts only, no positions (see parse_eradar_summary)
    # 1.53.4: an official alert message — "🟢 Відбій повітряної тривоги • Коростенський р-н • Житомирський р-н" — places
    # nothing, from a channel with an oblast of its own too (its raion lines were read as two targets, as a tracker's
    # bare place names are): the same rule as parse_post's
    nt = _norm(text)
    if ALERT_MSG_RX.search(nt) and not MOVE_RX.search(nt):
        return []
    # A notice that is plainly not about the sky — a press release, a metro timetable — places nothing, whichever
    # channel posted it and whichever parser would read it. (The softer news signs are left to the tagger: a live
    # tracker's short post can say "поранені" and still be a live report.)
    if NEWS_STRONG_RX.search(_norm(text)) or looks_like_explainer(_norm(text)) or FUNDRAISE_RX.search(_norm(text)):
        return []
    text = drop_friendly(text)                      # 1.43.1: our own drone is no target
    if not text:
        return []
    # 1.45: artillery and mortars ("артобстріл по Корабельному району Херсона з ТОТ") are not in the sky this app watches
    if ARTY_RX.search(_norm(text)) and not AIR_TARGET_RX.search(_norm(text)) and not re.search(r"fpv|фпв|ланцет|молні", _norm(text)):
        return []
    sp = _split_next(text)
    if sp:
        before, after = sp
        out = _parse_for_channel(channel, before, near)
        if after:
            nxt = _parse_for_channel(channel, after, near)
            if not nxt and len(after.split()) <= 6:
                # "Наступний Нивки": a bare place is the next target's position — in the channel's own oblast
                nxt = _parse_live(after, CHANNEL_HOME.get(channel) or "14")
            out += [m for m in nxt if not m.get("status")]
        return out
    fn = CHANNEL_PARSER.get(channel)
    home = CHANNEL_HOME.get(channel)
    if not fn and home and home not in ("31", "14"):
        fn = lambda t: _parse_live(t, home)          # noqa: E731
    if fn:
        r = fn(text)
        if r:
            return r
    r = parse_post(text, home if home not in ("31", "14") else None)
    if r or not near or not home or home in ("31", "14") or CHANNEL_PARSER.get(channel):
        return r
    for u in dict.fromkeys(near):
        if u != home and u in _REG_IDX:
            r = _parse_live(text, u)
            if r:
                for m in r:
                    ev = dict(m.get("evidence") or {})
                    pos = dict(ev.get("position") or {})
                    pos["method"] = (pos.get("method") or "") + " — read in the oblast this channel named just before"
                    ev["position"] = pos
                    m["evidence"] = ev
                return r
    return r


