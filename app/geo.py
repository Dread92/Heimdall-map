def _gender_ok(token, name):
    n = (name or "").split(" (")[0].strip().lower()
    if " " in n:
        return True
    t = (token or "").lower()
    if _NONFEM_NAME.search(n) and _FEM_TAIL.search(t):
        return False
    if _FEM_NAME.search(n) and _NONFEM_TAIL.search(t):
        return False
    return True


