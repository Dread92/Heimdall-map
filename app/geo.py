ALT_RX = [
    ("descending", re.compile(r"зниж\w*|знижуєть\w*|скида\w*\s+висот\w*|пікіру\w*|захід\s+на\s+ціль|заходить\s+на\s+ціль", re.I)),
    ("climbing", re.compile(r"набира\w*\s+висот\w*|підійма\w*|піднімаєть\w*", re.I)),
    ("low", re.compile(r"\bнизьк\w*\b|низько\s+йде|на\s+малій\s+висоті|гранично\s+мал\w*\s+висот\w*", re.I)),
    ("high", re.compile(r"\bвисоко\b|на\s+велик\w*\s+висот\w*|ешелон", re.I)),
]
# The channels write the height both ways round — "висота 2200" and "2200 висота" — and in a follow-up post
# they drop the word entirely: "1600, Вороньків". All three are read; nothing is guessed when none appear.
ALT_M_RX = re.compile(r"висот\w*\s*(?:бл\.|близько|~|приблизно)?\s*(\d{2,5})\s*(м|метр\w*|км)?"
                      r"|(\d{3,5})\s*(?:м|метр\w*)?\s*висот\w*", re.I)
# ...and in kilometres, often with a decimal comma: "висота 4,4км", "висота 5км" (war_monitor on jet drones).
# Read before the metre pattern, which cannot see a single digit and read "4,4км" as nothing at all.
ALT_KM_RX = re.compile(r"висот\w*\s*(?:бл\.|близько|~|приблизно)?\s*(\d{1,2}(?:[.,]\d{1,2})?)\s*км\b"
                       r"|(\d{1,2}(?:[.,]\d{1,2})?)\s*км\s*висот\w*", re.I)
# a lone 300–9000 in a short live post is a height, not a count: counts are written "3х" or "3 шахеди"
ALT_BARE_RX = re.compile(r"(?<![\d.,\-хx×])(\d{3,4})(?!\d|[.,]\d)", re.I)


def parse_altitude(seg):
    """Altitude / vertical behaviour, ONLY when the post states it.

    No public source publishes target altitude, so this is never inferred: a drone with nothing said about its
    height gets no altitude field at all, and the UI shows nothing rather than implying 'level flight'.
    Returned dict: {"state": descending|climbing|low|high, "m": metres or None, "matched": "<the words>"}."""
    out = None
    for state, rx in ALT_RX:
        m = rx.search(seg)
        if m:
            out = {"state": state, "m": None, "matched": m.group(0)}
            break
    mk = ALT_KM_RX.search(seg)
    mm = None if mk else ALT_M_RX.search(seg)
    v = None
    if mk:
        v = int(round(float((mk.group(1) or mk.group(2)).replace(",", ".")) * 1000))
        hit = mk
    elif mm:
        v = int(mm.group(1) or mm.group(3))
        if (mm.group(2) or "").lower().startswith("км"):
            v *= 1000
        hit = mm
    if v is not None and 10 <= v <= 20000:
        out = out or {"state": None, "matched": hit.group(0)}
        out["m"] = v
        out["matched"] = hit.group(0).strip()
    return out


def _alt_full(t):
    """1.52: the height and the vertical state together — "Хотів 1200 знижується" said both, and the descent took the
    place of the 1,200 m (the bare figure is read only when no worded height is)."""
    a = parse_altitude(t)
    if a and a.get("m"):
        return a
    b = parse_altitude_bare(re.sub(r"зниж\w*|знижуєть\w*|пікіру\w*|набира\w*|низьк\w*|низько|високо", " ", t, flags=re.I))
    if a and b:
        return dict(a, m=b["m"])
    return a or b


def parse_altitude_bare(t):
    """A follow-up post that is only a number and a place — '1600, Вороньків' — is a height report."""
    if len(t.split()) > 5 or re.search(r"висот|бпла|шахед|ракет|курс", t, re.I):
        return None
    m = ALT_BARE_RX.search(t)
    if not m:
        return None
    v = int(m.group(1))
    if 300 <= v <= 9000:
        return {"state": None, "m": v, "matched": m.group(1)}
    return None


# A post often reports clear sky AND a warning in the same breath:
#   "Чисте небо Київська область та Київ. Васильків увага ‼️"
# The places in the CLEAR sentence must never receive a threat marker — a false alarm over a city that was
# just declared clear is the worst kind of noise. Sentences are filtered before anything is parsed.
SENT_CLEAR_RX = re.compile(r"чист[еиої]\w*\s+небо|\bчисто\b|небо\s+чист|відбій|загроза\s+минула|небезпека\s+минула", re.I)


def _drop_clear_sentences(t):
    # 1.45: the sentences keep what separated them. Joined with spaces, the lines of an Air Force post ("🏍 … на Васильків
    # зі сходу.\n🏍 … на Ізяслав …") became one sentence, and every line after the first lost its target.
    toks = re.split(r"((?<=[.!?‼])\s+)", t)
    parts, seps = toks[0::2], toks[1::2] + [""]
    if len(parts) < 2:
        return t
    kept = [p + sp for p, sp in zip(parts, seps)
            if not (SENT_CLEAR_RX.search(p) and not re.search(r"увага|загроз|курс|летить|йде|бпла|ракет|каб", p[SENT_CLEAR_RX.search(p).end():] if SENT_CLEAR_RX.search(p) else ""))]
    return "".join(kept).strip() if kept else t


