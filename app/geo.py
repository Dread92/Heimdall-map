def _reg_stems(alias):
    """The stems an alias is looked up by: its own, and the alternations the core index adds (Лихачів/Лихачова)."""
    words = alias.split()
    if len(words) > 1:
        # every word of a two-word name declines ("Малую Даниловку", "Великої Данилівки"): stems of three letters and up
        def st3(x):
            x = x.strip("'-")
            while len(x) > 3 and x[-1] in VOWELS + "ыэй":
                x = x[:-1]
            return x
        return [" ".join(st3(x) for x in words)]
    st = _reg_stem_word(alias)
    out = [st]
    if st.endswith("ів"):
        out += [st[:-2] + "ов", st[:-2] + "ев"]
    elif st.endswith("їв"):
        out.append(st[:-2] + "єв")
    elif st.endswith("ін"):
        out.append(st[:-2] + "ен")
    elif st.endswith("ок"):
        out.append(st[:-2] + "к")
    elif st.endswith("ець"):
        out.append(st[:-3] + "ц")
        if st[:-3].endswith("л"):
            out.append(st[:-3] + "ьц")
    return out


def _ru_variants(alias):
    """The alias, and how a channel writing in Russian spells a Ukrainian village GeoNames gives no Russian name for:
    і as и, е or о (Лісне → Лесное, Пісочин → Песочин, Подвірки → Подворки), ї and є as и / е, no apostrophe
    (П'ятихатки → Пятихатки). Stems drop the endings, so Васищеве and Васищево are already the same word."""
    out = {alias}
    if not re.search(r"[іїє'ґ]", alias):
        return out
    if "'я" in alias:
        out.add(alias.replace("'я", "е"))          # Знам'янка → Знаменка
    base = alias.replace("'", "").replace("ґ", "г").replace("є", "е")
    slots = [i for i, c in enumerate(base) if c in "іїi"]
    if len(slots) > 3:
        slots = slots[:3]
    combos = [""]
    for _ in slots:
        combos = [c + x for c in combos for x in "иео"]
    for c in combos:
        b = list(base)
        for i, x in zip(slots, c):
            b[i] = x
        out.add("".join(b).replace("ї", "и"))
    return out


def _load_regional(path=None):
    path = path or os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data", "regional_places.json")
    try:
        with open(path, encoding="utf-8") as f:
            doc = json.load(f)
    except Exception:
        return
    core_norm = {}
    for n, v in dict.items(PLACES):
        core_norm.setdefault((_norm(n).split(" (")[0], v[2]), n)
    names = {}
    for uid, rows in doc.get("oblasts", {}).items():
        for r in rows:
            nm = r[0].replace("’", "'").replace("ʼ", "'")
            names.setdefault(nm, []).append((uid, [nm] + list(r[1:])))
    idx_all = {}
    for name, entries in names.items():
        for i, (uid, r) in enumerate(entries):
            _, lon, lat, kind, pop, raion, aliases = r
            core = core_norm.get((_norm(name), uid))
            if core:
                key = core               # a town the core gazetteer has: its Russian name now finds it too
            else:
                key = name if len(entries) == 1 and name not in PLACES else f"{name} ({raion})" if raion else f"{name} ({uid})"
                k2, n2 = key, 2
                while k2 in REGIONAL:
                    k2, n2 = f"{key} {n2}", n2 + 1
                key = k2
                REGIONAL[key] = (lon, lat, uid)
                _REG_META[key] = (kind, pop, raion)
            idx = idx_all.setdefault(uid, {})
            for a in {v for x in aliases for v in _ru_variants(_norm(x))}:
                if a in REGIONAL_STOP or len(a.replace(" ", "")) < 3:
                    continue
                for st in _reg_stems(a):
                    lst = idx.setdefault(st, [])
                    if (key, a) not in lst:
                        lst.append((key, a))
    _REG_IDX.update(idx_all)


# 1.45: the endings a declined name may carry after its stem (Ukrainian and Russian)
_REG_ENDINGS = frozenset(("", "а", "я", "у", "ю", "і", "ї", "и", "е", "є", "о", "й", "ь", "ы", "ам", "ям", "ах", "ях", "ою", "ею",
                          "єю", "ій", "ий", "ої", "ого", "ому", "им", "ім", "их", "ів", "їв", "ові", "еві", "єві", "ами",
                          "ями", "ом", "ем", "єм", "ой", "ей", "ую", "юю", "ая", "яя", "ое", "ее", "ые", "ых", "ым"))


# 1.43.1: words that are never half of a two-word village name. "З брянської новий буде" ("a new one will come from
# Bryansk oblast", @chernihiv_nebo) was read as the village Нова Буда — two-word names match on three-letter stems.
_REG_PAIR_STOP = frozenset("буде будуть був була було були йде іде йдуть ідуть летить летять є".split())


# 1.45: a raion named by its adjective — "БпЛА на Шепетівський район" (@radarhmel), "у Вознесенському районі" — is a place
# of its own: the raion, drawn at its centre town, shown as "Шепетівський р-н". Built from the raions of the regional
# gazetteer: the centre is the town the raion is named after (the core gazetteer's, or the village file's largest).
RAION_KEYS = {}        # oblast uid → {adjective stem "шепетівськ": key "Шепетівський р-н"}
_RAION_RX = re.compile(r"(?<![а-яіїєґ'\-])([а-яіїєґ'\-]{3,}?(?:ськ|цьк|зьк))(?:ий|ого|ому|им|ім|ій|ая|ой)\s+(?:р-н\w*|район\w*)")


def _load_raions():
    by_uid = {}
    for key, (kind, pop, raion) in _REG_META.items():
        if raion:
            by_uid.setdefault(REGIONAL[key][2], set()).add(raion)
    core = [(n, v) for n, v in dict.items(PLACES) if "(" not in n and not re.search(r"АЕС|ТЕС|ТЕЦ|ГЕС|аеро|водосх|масив|міст", n)]
    for uid, labels in by_uid.items():
        for label in labels:
            adj = _norm(label.replace(" р-н", ""))                      # "шепетівський"
            stem = re.sub(r"(?:ий|ій)$", "", adj)                       # "шепетівськ"
            base = re.sub(r"(?:ськ|цьк|зьк)$", "", stem)                 # "шепетів"
            centre = None
            tries = [x for x in (stem, base, base[:-1], base[:-2]) if len(x) >= 3]
            for b in tries:                 # the core gazetteer's town first, the shortest name (Рівне, not Рівненська АЕС)
                cands = sorted(((len(n), v[0], v[1]) for n, v in core if v[2] == uid and _norm(n).startswith(b)))
                if cands:
                    centre = cands[0][1:]
                    break
            if not centre:
                for b in tries:             # else the village file's largest place of that raion named so
                    cands = [(REGIONAL[k][0], REGIONAL[k][1]) for k, m in sorted(_REG_META.items(), key=lambda x: -x[1][1])
                             if REGIONAL[k][2] == uid and m[0] in ("A", "P") and _norm(k).startswith(b) and m[2] == label][:1]
                    if cands:
                        centre = cands[0]
                        break
            if centre and label not in REGIONAL:
                REGIONAL[label] = (centre[0], centre[1], uid)
                _REG_META[label] = ("R", 0, label)
                RAION_KEYS.setdefault(uid, {})[stem] = label


def _reg_lookup(idx, words):
    """Keys whose alias these words (one, or two in a row) are a declined form of."""
    keys = []
    if len(words) == 1:
        w = words[0]
        if w in REGIONAL_STOP:
            return []
        adj = bool(_ADJ_NOT_NEUTER_RX.search(w))
        exact = []
        for k in range(0, 4):
            st = w[:len(w) - k]
            if len(st) < 3 or (len(st) < 4 and k):
                break
            # 1.45: what follows the stem must be an ending — "Боровиця" is not a form of "Борове" (stem "боров" + "иця")
            if w[len(st):] not in _REG_ENDINGS:
                continue
            for key, alias in idx.get(st, ()):
                if adj and alias.endswith(("ське", "цьке", "зьке", "ское", "цкое")):
                    continue
                if alias == w and key not in exact:
                    exact.append(key)
                # 1.44.1: a Russian name declined like an adjective — "Раздельная": "в сторону Раздельной", "на Раздельную"
                ru_adj = alias.endswith(("ая", "яя")) and w[:len(alias) - 2] == alias[:-2] and \
                    w[len(alias) - 2:] in ("ая", "ой", "ую", "ей", "юю", "яя", "ою")
                if (len(st) >= 4 or st == alias) and (ru_adj or _plausible(w, alias, st)) and key not in keys:
                    keys.append(key)
        # 1.45: the name exactly as written wins over its look-alikes — "на Високе" is Високе, not Висока
        return exact or keys
    w1, w2 = words
    if w1 in _REG_PAIR_STOP or w2 in _REG_PAIR_STOP:
        return []
    for k1 in range(0, 4):
        a = w1[:len(w1) - k1]
        if len(a) < 3:
            break
        for k2 in range(0, 4):
            b = w2[:len(w2) - k2]
            if len(b) < 3:
                break
            for key, alias in idx.get(a + " " + b, ()):
                if key not in keys:
                    keys.append(key)
    return keys


def _find_regional(text, uid):
    """(start, end, [keys]) for every regional name of oblast `uid` the text holds."""
    idx = _REG_IDX.get(uid)
    out = []
    for stem, key in (REGIONAL_WORDS.get(uid) or {}).items():
        for m in re.finditer(r"(?<![а-яіїєґ'\-])" + re.escape(stem) + r"[а-яіїєґ']{0,3}(?![а-яіїєґ'\-])", text):
            out.append((m.start(), m.end(), [key]))
    if not idx:
        return out
    toks = [(m.start(), m.end(), m.group(0)) for m in _REG_TOK.finditer(text)]
    levels = {m.start() for m in _LEVEL_RX.finditer(text)}
    for i, (s0, e0, w) in enumerate(toks):
        if s0 in levels:
            continue
        keys = _reg_lookup(idx, [w])
        if keys:
            out.append((s0, e0, keys))
        if i + 1 < len(toks) and not text[e0:toks[i + 1][0]].strip():
            keys = _reg_lookup(idx, [w, toks[i + 1][2]])
            if keys:
                out.append((s0, toks[i + 1][1], keys))
    for m in _REG_ABBR_RX.finditer(text):
        keys = _reg_lookup(idx, ["велика" if m.group(1) == "в" else "мала", m.group(2)])
        if keys:
            out.append((m.start(), m.end(), keys))
    for m in _RAION_RX.finditer(text):
        key = (RAION_KEYS.get(uid) or {}).get(m.group(1))
        if key:
            out.append((m.start(), m.end(), [key]))
    return out


def _ambig_token(keys, uid, said="", default=None):
    """Several villages of the oblast share the name: one token, its candidates best first, and whether one of them
    is clearly the one a post means without more to go on — the only admin centre, the only city district, or a
    population three times the next."""
    # the name shown is the one the post used, when one candidate is called that ("Привітне", not the old name of a
    # renamed village that GeoNames also lists under it)
    st = _reg_stem_word(_norm(said))[:5]
    base = next((k.split(" (")[0] for k in keys if st and _norm(k).startswith(st)), keys[0].split(" (")[0])
    meta = [(k, _REG_META.get(k, ("P", 0, ""))) for k in keys]
    admin = [k for k, m in meta if m[0] == "A"]
    city = [k for k, m in meta if m[0] == "X"]
    pops = sorted(meta, key=lambda x: -x[1][1])
    if default:
        pass                         # given: a core town against hamlets of its name (_find_places)
    elif len(city) == 1:
        default = city[0]            # a channel of the oblast naming a district of its city ("Алексеевка", Kharkiv)
    elif len(admin) == 1:
        default = admin[0]
    elif pops[0][1][1] >= 1000 and pops[0][1][1] >= 3 * (pops[1][1][1] if len(pops) > 1 else 0):
        default = pops[0][0]
    rest = [k for k, _ in pops if k != default]
    if not default:
        rest.sort(key=lambda k: k.split(" (")[0] != base)     # the candidates called what the post said, first
    order = ([default] if default else []) + rest
    tok = f"≈{base}|{uid}|{len(AMBIG)}"
    AMBIG[tok] = {"name": base, "uid": uid, "keys": order, "default": bool(default)}
    REGIONAL[tok] = PLACES[order[0]]
    if len(AMBIG) > 5000:            # tokens are per post; a long-running process must not keep every one
        for t in list(AMBIG)[:2500]:
            AMBIG.pop(t, None)
            REGIONAL.pop(t, None)
    return tok


def _km(a, b):
    """Distance in km between two (lon, lat) points — flat-earth, fine at the scale of an oblast."""
    return math.hypot((a[0] - b[0]) * 111.0 * math.cos(math.radians((a[1] + b[1]) / 2)), (a[1] - b[1]) * 111.0)


def villages(uids, min_pop=1000):
    """1.45: the map's "villages and small towns" layer outside Kyiv oblast — the regional gazetteer's hromada
    centres and places of at least `min_pop` people in the given oblasts, as (name, lon, lat, oblast uid).
    The core gazetteer's towns are not repeated (a regional entry that matched one was never added)."""
    out = []
    for key, (kind, pop, _raion) in _REG_META.items():
        lon, lat, uid = REGIONAL[key]
        if uid not in uids or kind not in ("A", "P") or not (kind == "A" or (pop or 0) >= min_pop):
            continue
        out.append((re.sub(r" \d+$", "", key.split(" (")[0]), lon, lat, uid, kind == "A", pop or 0))
    # hromada centres first, then the largest: the map's label layout keeps the first of two names that collide
    out.sort(key=lambda r: (not r[4], -r[5]))
    return [r[:4] for r in out]


def display_place(name):
    """What the reader sees for a place key: the ambiguity token's plain name."""
    if not name:
        return name
    pre = "→ " if name.startswith("→ ") else ""
    n = name[len(pre):]
    if n in AMBIG:
        return pre + AMBIG[n]["name"]
    return name


def bearing(lon1, lat1, lon2, lat2):
    y = math.sin(math.radians(lon2 - lon1)) * math.cos(math.radians(lat2))
    x = math.cos(math.radians(lat1)) * math.sin(math.radians(lat2)) - math.sin(math.radians(lat1)) * math.cos(math.radians(lat2)) * math.cos(math.radians(lon2 - lon1))
    return (math.degrees(math.atan2(y, x)) + 360) % 360


# Several Kyiv places share a name with an oblast adjective — "Житомирська" is a metro station on the red
# line and also the way every post refers to Zhytomyr oblast. Читаючи його як станцію, the app planted a
# marker 9 km from Kyiv for a post about a forest service in Olevsk, 150 km away. When the oblast noun
# follows, the word is the oblast.
_OBLAST_NOUN_RX = re.compile(r"\s*(?:обл\.|област|обласн|ова\b|овадміністрац|рад[аиі]\b|облрад)", re.I)


def _uid_for(where, obl):
    """The oblast of the place actually matched; the sentence's oblast only fills a gap it cannot contradict."""
    own = PLACES.get((where or "").replace("\u2192 ", ""), (0, 0, None))[2]
    if own:
        return own
    return obl[1] if obl else None


def _find_places(text, ctx_uid=None):
    """Return list of (start, end, name) for places mentioned in text, non-overlapping.
    Ambiguous names (same stem in several oblasts) are resolved with ctx_uid, else the plain (unparenthesised) entry."""
    spans = {}
    for rx, name, base in _INDEX:
        for m in rx.finditer(text):
            if not _plausible(m.group(0), name, base):
                continue
            if _OBLAST_NOUN_RX.match(text, m.end()) and "трас" not in name.lower():
                continue          # "Житомирська область" is the oblast, not the Kyiv metro station
            if not _gender_ok(m.group(0), name):
                continue
            if name in _METRO_ONLY and not (_METRO_BEFORE.search(text[max(0, m.start() - 16):m.start()]) or _METRO_AFTER.match(text, m.end())):
                continue          # 1.54.2: the oblast, unless the post says metro
            key = (m.start(), m.end())
            spans.setdefault(key, []).append(name)
    # 1.43: the villages of the oblast the post is about (its channel's, or the one it names) — only then.
    # 1.54.7: a Kyiv tracker (ctx "31") reports the whole of Kyiv oblast too — its villages are read with the city's
    area = ("31", "14") if ctx_uid == "31" else (ctx_uid,) if ctx_uid else ()
    for ru in area:
        if not (ru in _REG_IDX or ru in REGIONAL_WORDS):
            continue
        for s0, e0, ks in _find_regional(text, ru):
            if _OBLAST_NOUN_RX.match(text, e0):
                continue
            ks = [k for k in ks if _gender_ok(text[s0:e0].split()[-1], k)]
            if not ks:
                continue
            lst = spans.setdefault((s0, e0), [])
            lst.extend(k for k in ks if k not in lst)
    # drop spans overlapped by a longer span
    keys = sorted(spans, key=lambda k: (k[0], -(k[1] - k[0])))
    found = []
    taken = []
    for k in keys:
        if any(s < k[1] and k[0] < e for s, e in taken):
            continue
        taken.append(k)
        names = spans[k]
        pick = None
        if ctx_uid:
            own = [n for n in names if PLACES[n][2] == ctx_uid]
            core = [n for n in own if dict.__contains__(PLACES, n)]
            # 1.54.7: a Kyiv tracker's village of Kyiv oblast — the one place of that name when no town of the gazetteer
            # has it ("Кулажинці", "Мощун"); a district of Kyiv and villages of the oblast with its name ("лук'янівка",
            # @chyste_nebo, 01:12, was the village east of Brovary, not Lukyanivka in Kyiv): the district stays the
            # default, and the server takes the one next to the channel's reports before and after (the candidates)
            vill = [n for n in names if ctx_uid == "31" and not dict.__contains__(PLACES, n) and PLACES[n][2] == "14"]
            if vill and not own and not any(dict.__contains__(PLACES, n) for n in names):
                own = vill
            vill = [n for n in vill if core and _norm(n.split(" (")[0]) == _norm(core[0].split(" (")[0])]
            # 1.43.1: a town of the core gazetteer in the next oblast, against small villages of this one that share
            # its name: "На Таращу" from the Cherkasy tracker is the town of Тараща in Kyiv oblast, where the drones
            # leave Cherkasy oblast — not the hamlet of the same name — unless the channel's previous report or the
            # other places of the post are next to the village (the candidates, as for any shared name)
            said = _norm(text[k[0]:k[1]])
            other = [n for n in names if "(" not in n and dict.__contains__(PLACES, n) and PLACES[n][2] != ctx_uid
                     and own and _norm(n) in (_norm(own[0].split(" (")[0]), said)]   # the same name (or the word as written)
            if core and vill and ctx_uid == "31":
                pick = _ambig_token(core[:1] + vill, ctx_uid, text[k[0]:k[1]], default=core[0])
            elif core:
                pick = core[0]               # the town the core gazetteer lists, over a village of the same name
            elif own and other and all(_REG_META.get(o, ("P", 0, ""))[0] == "P" and _REG_META.get(o, ("P", 0, ""))[1] < 2000
                                       for o in own):
                pick = _ambig_token(other[:1] + own, ctx_uid, text[k[0]:k[1]], default=other[0])
            elif len(own) > 1:
                pick = _ambig_token(own, ctx_uid, text[k[0]:k[1]])
            elif own:
                pick = own[0]
        if pick is None:
            plain = [n for n in names if "(" not in n and dict.__contains__(PLACES, n)]
            pick = plain[0] if plain else names[0]
        found.append((k[0], k[1], pick))
    found.sort()
    # A name several villages share is the one near the other places the same post names ("На Добрянку-Олешню":
    # the Олешня next to Добрянка, not the one 100 km east). Nothing else near: left to the channel's previous report.
    fixed = [PLACES[n][:2] for _, _, n in found if n not in AMBIG] or \
        [PLACES[AMBIG[n]["keys"][0]][:2] for _, _, n in found if n in AMBIG and AMBIG[n]["default"]]
    if fixed and len(found) > 1:
        for i, (s0, e0, n) in enumerate(found):
            if n in AMBIG:
                best = min(AMBIG[n]["keys"], key=lambda c: min(_km(PLACES[c][:2], f) for f in fixed))
                if min(_km(PLACES[best][:2], f) for f in fixed) <= _REG_KM:
                    found[i] = (s0, e0, best)
    return found


# "Реактивні БпЛА на півночі Київщини" says where in the oblast, and the app used to drop the marker on the
# oblast centre anyway — which for Kyiv oblast lands near Vasylkiv, in the south. A quadrant the post states
# is information, and dropping it is the same failure as inventing one. This matches only LOCATION phrasing:
# "у західному напрямку" is a course, not a place, and must never move the marker.
OBL_QUAD_RX = re.compile(
    r"(?:на|у|в)\s+(північн|східн|західн|південн)\w*\s*(?:-\s*(східн|західн)\w*)?\s*(?:частин|краю|межах)"
    r"|(?:на)\s+(півноч|сход|заход|півдн)і(?!\w*\s+напрям)"
    r"|(північ|схід|захід|південь)\s+(?:області|облісті)", re.I)
_QUAD_D = {"північн": (0, 1), "півноч": (0, 1), "північ": (0, 1),
           "південн": (0, -1), "півдн": (0, -1), "південь": (0, -1),
           "східн": (1, 0), "сход": (1, 0), "схід": (1, 0),
           "західн": (-1, 0), "заход": (-1, 0), "захід": (-1, 0)}
# roughly half an oblast: far enough that "north" is visibly north, short enough to stay inside the oblast
QUAD_DLON, QUAD_DLAT = 0.85, 0.55


# Some channels write the "A/B" pair with a compass word where the town would go: "Одещина: ➡️Південь/Одеса"
# means the south of Odesa oblast, heading for Odesa. With no town to match, the marker used to land on the
# oblast centre — so a drone the channel had placed in the south was drawn 90 km north of it, and every such
# line in a raid piled up on the same pixel. Only these exact forms count: "південне" is a town, not a side.
_QUAD_EXACT = {
    "пн": (0, 1), "північ": (0, 1), "півночі": (0, 1), "північна": (0, 1), "північну": (0, 1), "північно": (0, 1),
    "пд": (0, -1), "південь": (0, -1), "півдня": (0, -1), "півдні": (0, -1), "південна": (0, -1), "південно": (0, -1),
    "сх": (1, 0), "схід": (1, 0), "сходу": (1, 0), "східна": (1, 0), "східно": (1, 0),
    "зх": (-1, 0), "зах": (-1, 0), "захід": (-1, 0), "заходу": (-1, 0), "західна": (-1, 0), "західно": (-1, 0),
}


def bare_quadrant(seg):
    """(dlon, dlat, key) when a segment is NOTHING BUT a compass word (or two), else None."""
    toks = [x for x in re.split(r"[^а-яіїєґ']+", seg.lower()) if x]
    if not toks or len(toks) > 2:
        return None
    dx = dy = 0
    for tk in toks:
        d = _QUAD_EXACT.get(tk)
        if not d:
            return None
        dx += d[0]
        dy += d[1]
    if not dx and not dy:
        return None
    key = ("n" if dy > 0 else "s" if dy < 0 else "") + ("e" if dx > 0 else "w" if dx < 0 else "")
    return (dx * QUAD_DLON, dy * QUAD_DLAT, key)


def oblast_quadrant(text):
    """(dlon, dlat, key) for a stated part of an oblast, or None. Never derived from a course word."""
    m = OBL_QUAD_RX.search(text)
    if not m:
        return None
    parts = [g for g in m.groups() if g]
    dx = dy = 0
    for g in parts:
        d = _QUAD_D.get(g.lower())
        if d:
            dx += d[0]
            dy += d[1]
    if not dx and not dy:
        return None
    key = ("n" if dy > 0 else "s" if dy < 0 else "") + ("e" if dx > 0 else "w" if dx < 0 else "")
    return (dx * QUAD_DLON, dy * QUAD_DLAT, key)


# "Далі Київщина" / "потім Чернігівщина" — the monitors write the CONTINUATION of the route this way. The
# oblast after such a word is where the target is going next, never where it is now. Reading it as a position
# is how three Banderols reported north of Nizhyn were also drawn at the centre of Kyiv oblast, 150 km away:
# one flight, two markers, and the second one over a region nothing had been reported in.
_ONWARD_RX = re.compile(r"(?:дал[іе]|пот[іи]м|згодом|надал[іі]|наступн\w*|прямує\s+(?:до|в|у)|курс\w*\s+на|"
                         # 1.45: "2 реактивних повз Смоліне вилітають на Черкащину" (@controlkrop) — where it goes next
                         r"(?:ви|за|пере)літа\w*\s+(?:на|в|у|до)|(?:ви|за|пере)лет\w*\s+(?:на|в|у|до))\W{0,4}$")


def _onward(text, pos):
    """Is the oblast that starts at `pos` introduced as the NEXT area rather than the current one?"""
    return bool(_ONWARD_RX.search(text[max(0, pos - 24):pos]))


def _find_oblasts_all(text, positional=False):
    res = []
    for stem, uid, lon, lat in OBLAST_ADJ:
        for m in re.finditer(stem, text):
            if positional and _onward(text, m.start()):
                continue
            res.append((m.start(), uid, lon, lat))
    return sorted(res)


def _find_oblast(text, positional=False):
    best = None
    for stem, uid, lon, lat in OBLAST_ADJ:
        for m in re.finditer(stem, text):
            if positional and _onward(text, m.start()):
                continue
            if best is None or m.start() < best[0]:
                best = (m.start(), uid, lon, lat)
            break
    return best


# Where a place stands in a sentence. "на Васильків", "на Бучу", "на Позняки", "в район Василькова", "до Києва":
# where it is GOING. "від Глевахи", "з Обухова", "повз Кагарлик", "над Ірпенем", "в районі Броварів": where it IS.
# 25 Sep 2026: "реактивний БпЛА на Васильків з північного заходу" — still north-west of Vasylkiv, on its way in —
# was drawn ON Vasylkiv, turned south-east, and read as a drone that had already passed it.
# After "на" a place in the locative says where it is, not where it goes: "на Позняках", "на Троєщині", "на Лісовій".
_LOC_END = re.compile(r"(?:і|ї|ах|ях|ій)$")
# 1.45: "2х вектор Велика Димерка/Бровари" — the Kyiv channels' "вектор" is a course, like "курсом"
_DEST_PRE = re.compile(r"(?:\bна|\bв район|\bу район|\bдо|\bв напрямку|\bу напрямку|\bв бік|\bу бік|\bв сторону|\bвектор(?:ом)?|→|➡️?)\s*$")
_FROM_PRE = re.compile(r"(?:\bвід|\bз|\bзі|\bповз|\bнад|\bбіля|\bпоблизу|\bрайоні|\bр-ні)\s+$")
_FROM_COMPASS = re.compile(r"\b(?:з|зі|від)\s+((?:півн|півд|сх|зах)[а-яіїє'-]*(?:[\s-]+(?:сх|зах)[а-яіїє'-]*)?)")


def _place_role(text, p):
    """'dest' (it is heading there), 'from' (it is there, or came from there) or None (a bare name) for a place
    match (start, end, name), from the words just before it."""
    pre = text[max(0, p[0] - 16):p[0]]
    m = _DEST_PRE.search(pre)
    if m:
        if m.group(0).strip() == "на" and _LOC_END.search(text[p[0]:p[1]].strip()):
            return None
        return "dest"
    if _FROM_PRE.search(pre):
        return "from"
    return None


def _dir(s):
    """Compass heading (deg) from a Ukrainian phrase, or None."""
    n = "півн" in s
    so = "півд" in s
    e = "сх" in s
    w = "зах" in s
    if n and e: return 45
    if n and w: return 315
    if so and e: return 135
    if so and w: return 225
    if n: return 0
    if so: return 180
    if e: return 90
    if w: return 270
    return None


def _sub_direction_offset(text, pos):
    """'на півночі Вінниччини' -> offset (dlon, dlat) of ~70 km toward that side."""
    before = text[max(0, pos - 30):pos]
    m = re.search(r"(?:на|у|в)\s+([а-яіїє'-]+(?:\s+[а-яіїє'-]+)?)\s*$", before)
    if not m:
        return (0, 0)
    deg = _dir(m.group(1))
    if deg is None:
        return (0, 0)
    return (0.9 * math.sin(math.radians(deg)), 0.6 * math.cos(math.radians(deg)))


